def _scan(text: str, rules: dict) -> list:
    """按关键词表扫描文本，返回命中的标签。"""
    hits = []
    for label, keywords in rules.items():
        if any(kw in text for kw in keywords):
            hits.append(label)
    return hits


def extract_tags(title: str = "", summary: str = "", asr_text: str = "") -> dict:
    """从视频文本里提取人群标签。

    返回结构与 LLM 版 video_tagger 一致，confidence 固定为 0.8（规则命中）。
    """
    # 全文窗口：标题、简介权重最高，转写取前 12000 字
    full = " ".join([title, summary, asr_text[:12000]])
    return {
        "face_shapes": _scan(full, FACE_SHAPE_RULES),
        "feature_tags": _scan(full, FEATURE_RULES),
        "pain_points": _scan(full, PAIN_POINT_RULES),
        "style": _scan(full, STYLE_RULES),
        "difficulty": _scan(full, DIFFICULTY_RULES),
        "confidence": 0.8,
    }
